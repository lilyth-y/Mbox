#!/usr/bin/env node
/**
 * Writes apps/web/public/wedding-simple/cube-config.js from shared defaults.
 * Keep in sync with packages/shared/src/cubePresentationDefaults.ts
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPaths = [
  join(root, "apps/web/public/wedding-simple/cube-config.js"),
  join(root, "wedding-simple/cube-config.js"),
];

/** Mirror of DEFAULT_CUBE_PRESENTATION_OPTIONS */
const d = {
  framePresetId: "rose_gold",
  hologramMode: false,
  particleTheme: "none",
  voluMaxDepthEnabled: false,
  voluMaxFxEnabled: false,
  voluMaxAutoPrepareLayers: false,
  voluMaxAiForegroundCutout: true,
  backgroundPlateTheme: "original",
  bgmEnabled: false,
  cubeRotationMode: "yaw_cw",
};

const framework = {
  safetyWeight: 7,
  qualityWeight: 3,
  parallaxAllowedPhases: ["showcase_hold"],
  parallaxPeakMax: 0.34,
  parallaxFgMulVolumax: 0.095,
  parallaxBgMulVolumax: 0.082,
  facePhotoZ: 0.018,
  faceBgZ: -0.022,
  focusPulseZMax: 0.048,
  faceUvInset: 0.038,
  faceContentScale: 0.94,
  volumaxAlphaTest: 0.08,
  originalPlateBlurPx: 22,
};

const js = `/** Auto-generated by scripts/sync-cube-config.mjs — do not edit by hand. */
window.MBOX_CUBE_EFFECT_FRAMEWORK = ${JSON.stringify(framework, null, 2)};
window.MBOX_CUBE_PRESENTATION_DEFAULTS = ${JSON.stringify(
  {
    presentationEffectId: "cube_focus",
    framePresetId: d.framePresetId,
    customFrameColor: "",
    backgroundTheme: d.backgroundPlateTheme,
    backgroundPlateTheme: d.backgroundPlateTheme,
    particleTheme: d.particleTheme,
    bgmTrackId: "none",
    hologramMode: d.hologramMode,
    voluMaxDepthEnabled: d.voluMaxDepthEnabled,
    voluMaxFxEnabled: d.voluMaxFxEnabled,
    voluMaxAutoPrepareLayers: d.voluMaxAutoPrepareLayers,
    voluMaxAiForegroundCutout: d.voluMaxAiForegroundCutout,
    cubeRotationMode: d.cubeRotationMode,
    fanSpeed: 1,
  },
  null,
  2
)};
`;

for (const outPath of outPaths) {
  writeFileSync(outPath, js, "utf8");
  console.log(`Wrote ${outPath}`);
}
